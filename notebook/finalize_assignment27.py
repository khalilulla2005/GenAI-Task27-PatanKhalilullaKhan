# Code: Tasks 3/4
code_cell_3 = nbf.v4.new_code_cell("""# Task 4: Trimming
def trim_history(messages, max_messages=4):
    return messages[-max_messages:]

# Simulate long history
long_history = [HumanMessage(content=f"Msg {i}") for i in range(10)]
trimmed = trim_history(long_history)

print("=== Task 4: Trimming Results ===")
print(f"Original length: {len(long_history)}, Trimmed length: {len(trimmed)}")
print(f"Last 4 messages: {trimmed}")
""")

